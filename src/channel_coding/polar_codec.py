"""
Polar Channel Coding Module using Arikan Polar Codes and Successive Cancellation Decoding.

Mathematical Formulation & Architecture:
----------------------------------------
Polar codes, introduced by Erdal Arikan (2009), are the first mathematically proven
capacity-achieving forward error correction (FEC) codes for symmetric binary-input
discrete memoryless channels (B-DMC) under low-complexity Successive Cancellation (SC)
decoding. They were standardized by 3GPP for the 5G NR control channels.

1. Arikan Kernel & Generator Matrix:
   The polarization transformation is defined recursively by the Arikan 2x2 kernel:
       G_2 = [[1, 0],
              [1, 1]]
   For block length N = 2^n (n >= 1), the n-th Kronecker power is:
       G_N = G_2^{\\otimes n}
   Channel polarization transforms N independent copies of the physical channel into
   N polarized synthetic bit-channels W_N^{(i)} whose mutual information tends toward
   either 0 (completely noisy / frozen channels) or 1 (completely reliable / information channels)
   as N -> infinity.

2. Code Parameters & Frozen Bit Construction:
   - Codeword block length N: Must be a power of 2 (N = 2^n, e.g., 64, 128, 256, 512, 1024).
   - Information block length K: Number of information bits transmitted per block (1 <= K < N).
   - Code rate: R = K / N.
   - Frozen bit set F: The N - K least reliable bit-channel indices, fixed to a known value
     (conventionally 0).
   - Information set A: The K most reliable bit-channel indices.
   - Reliability ordering is computed via Arikan's Bhattacharyya Bounds ('bb') or
     Gaussian Approximation ('ga') for a specified design SNR.

3. Encoding:
   Given information vector u_A of length K and frozen vector u_F = 0 of length N - K:
   The uncoded vector u in {0, 1}^N is formed by placing information bits at indices A
   and 0 at indices F.
   The transmitted codeword x of length N is generated by:
       x = u * G_N  (modulo 2)
   In systematic polar coding, an additional transform ensures that the information bits
   appear directly in the codeword x.

4. Log-Likelihood Ratio (LLR) & Decoding Convention:
   The Successive Cancellation Decoder (SCD) consumes channel soft values defined as:
       LLR(y) = ln( P(y | bit=0) / P(y | bit=1) )
   Conventions:
   - LLR > 0: Bit 0 is more probable.
   - LLR < 0: Bit 1 is more probable.
   - Hard decision: hard_decision(LLR) = 0 if LLR >= 0 else 1.
   - Noiseless transmission: Bit 0 -> +LLR_max, Bit 1 -> -LLR_max.

5. Arbitrary-Length Messages & Padding:
   Binary messages exceeding K bits are partitioned into sequential blocks of length K.
   If the final block has fewer than K bits, it is zero-padded to K bits. The decoder
   processes each N-bit codeword block and removes the trailing padding bits.

References:
- Arikan, E. (2009). Channel polarization: A method for constructing capacity-achieving
  codes for symmetric binary-input memoryless channels. IEEE Trans. Inf. Theory, 55(7).
- McBain, B. (2020). py-polar-codes: A Python Library for Polar Codes. MIT License.
"""

from dataclasses import dataclass
from typing import Optional, Sequence, Tuple, Union
import numpy as np
import polarcodes
from polarcodes import Construct, Decode, Encode, PolarCode

from src.utils.bit_utils import pad_bits, unpad_bits


# ---------------------------------------------------------------------------
# Custom Exceptions
# ---------------------------------------------------------------------------
class PolarError(Exception):
    """Base exception for Polar coding errors."""
    pass


class PolarConfigurationError(PolarError):
    """Raised when Polar code parameters are invalid or unsupported."""
    pass


class PolarEncodingError(PolarError):
    """Raised when encoding fails due to dimension or value errors."""
    pass


class PolarDecodingError(PolarError):
    """Raised when decoding fails due to corrupted inputs or state."""
    pass


# ---------------------------------------------------------------------------
# Configuration Dataclass
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class PolarConfig:
    """
    Configuration parameters for Arikan Polar Code.

    Attributes
    ----------
    N : int
        Codeword block length. Must be a power of 2 (e.g., 64, 128, 256, 512, 1024).
    K : int
        Information length. Number of information bits per block (1 <= K < N).
    design_snr_db : float, default=2.0
        Design Signal-to-Noise Ratio (Eb/N0 in dB) for Bhattacharyya reliability sorting.
    construction_type : str, default='bb'
        Code construction method: 'bb' (Bhattacharyya Bounds) or 'ga' (Gaussian Approximation).
    systematic : bool, default=False
        If True, use systematic polar encoding; if False, standard non-systematic.
    noiseless_llr : float, default=100.0
        Magnitude of soft LLR assigned to noiseless binary bits (+100 for 0, -100 for 1).
    """
    N: int = 128
    K: int = 64
    design_snr_db: float = 2.0
    construction_type: str = "bb"
    systematic: bool = False
    noiseless_llr: float = 100.0

    def __post_init__(self) -> None:
        # Validate N is positive power of 2
        if not isinstance(self.N, (int, np.integer)) or self.N <= 1:
            raise PolarConfigurationError(f"Block length N must be an integer > 1, got {self.N}")

        n = np.log2(self.N)
        if np.ceil(n) != np.floor(n):
            raise PolarConfigurationError(
                f"Block length N must be a power of 2 (e.g. 64, 128, 256), got {self.N}"
            )

        # Validate K
        if not isinstance(self.K, (int, np.integer)) or self.K < 1 or self.K >= self.N:
            raise PolarConfigurationError(
                f"Information length K must satisfy 1 <= K < N ({self.N}), got {self.K}"
            )

        # Validate construction type
        valid_constructions = ("bb", "ga")
        if self.construction_type not in valid_constructions:
            raise PolarConfigurationError(
                f"construction_type must be one of {valid_constructions}, got {self.construction_type!r}"
            )

        # Validate LLR magnitude
        if self.noiseless_llr <= 0:
            raise PolarConfigurationError(
                f"noiseless_llr must be strictly positive, got {self.noiseless_llr}"
            )

    @property
    def code_rate(self) -> float:
        """Code rate R = K / N."""
        return float(self.K) / float(self.N)


# ---------------------------------------------------------------------------
# Helper Utility Functions
# ---------------------------------------------------------------------------
def bits_to_llr(
    bits: Union[np.ndarray, Sequence[int]],
    magnitude: float = 100.0,
) -> np.ndarray:
    """
    Convert binary bits {0, 1} into channel LLR values under noiseless conditions.

    Convention:
        bit 0 -> +magnitude
        bit 1 -> -magnitude
    """
    arr = np.asarray(bits, dtype=np.uint8)
    if not np.all((arr == 0) | (arr == 1)):
        raise ValueError("Bits array must contain only 0s and 1s.")
    return np.where(arr == 0, float(magnitude), -float(magnitude)).astype(np.float64)


def llr_to_hard_bits(llrs: Union[np.ndarray, Sequence[float]]) -> np.ndarray:
    """
    Perform hard decision slicing on soft LLRs: LLR >= 0 -> 0, LLR < 0 -> 1.
    """
    arr = np.asarray(llrs, dtype=np.float64)
    return np.where(arr >= 0.0, 0, 1).astype(np.uint8)


# ---------------------------------------------------------------------------
# Polar Codec Implementation
# ---------------------------------------------------------------------------
class PolarCodec:
    """
    Arikan Polar Forward Error Correction (FEC) Encoder and SCD Decoder.

    Wraps the validated py-polar-codes engine with typed APIs, dimension checking,
    stream block-partitioning, and padding support.
    """

    def __init__(
        self,
        config: Optional[PolarConfig] = None,
        N: Optional[int] = None,
        K: Optional[int] = None,
        design_snr_db: Optional[float] = None,
        construction_type: Optional[str] = None,
        systematic: Optional[bool] = None,
        noiseless_llr: Optional[float] = None,
    ) -> None:
        if config is None:
            # Build config from individual arguments or use defaults
            kwargs = {}
            if N is not None:
                kwargs["N"] = N
            if K is not None:
                kwargs["K"] = K
            if design_snr_db is not None:
                kwargs["design_snr_db"] = design_snr_db
            if construction_type is not None:
                kwargs["construction_type"] = construction_type
            if systematic is not None:
                kwargs["systematic"] = systematic
            if noiseless_llr is not None:
                kwargs["noiseless_llr"] = noiseless_llr
            self._config = PolarConfig(**kwargs)
        else:
            self._config = config

        self._pc = self._build_polar_instance()

    def _build_polar_instance(self) -> PolarCode:
        """Instantiate and construct underlying PolarCode object."""
        pc = PolarCode(self._config.N, self._config.K)
        pc.construction_type = self._config.construction_type
        Construct(pc, design_SNR=self._config.design_snr_db)
        return pc

    @property
    def config(self) -> PolarConfig:
        return self._config

    @property
    def N(self) -> int:
        return self._config.N

    @property
    def K(self) -> int:
        return self._config.K

    @property
    def code_rate(self) -> float:
        return self._config.code_rate

    @property
    def frozen_indices(self) -> np.ndarray:
        """Indices of frozen bit-channels."""
        return self._pc.frozen.copy()

    @property
    def info_indices(self) -> np.ndarray:
        """Indices of information bit-channels."""
        return np.where(self._pc.frozen_lookup == 1)[0]

    # -----------------------------------------------------------------------
    # Single-Block Operations
    # -----------------------------------------------------------------------
    def encode_block(self, message: Union[np.ndarray, Sequence[int]]) -> np.ndarray:
        """
        Encode a single block of exactly K information bits into an N-bit codeword.

        Parameters
        ----------
        message : np.ndarray or Sequence[int]
            1D array of length K containing binary elements {0, 1}.

        Returns
        -------
        np.ndarray
            1D array of length N containing binary codeword bits (uint8).
        """
        arr = np.asarray(message, dtype=np.uint8)
        if arr.ndim != 1 or arr.size != self._config.K:
            raise PolarEncodingError(
                f"encode_block expects 1D array of length K={self._config.K}, "
                f"got shape={arr.shape}"
            )

        if not np.all((arr == 0) | (arr == 1)):
            raise PolarEncodingError("encode_block input message must contain only 0s and 1s")

        self._pc.set_message(arr.astype(int))
        enc_name = "systematic_encode" if self._config.systematic else "polar_encode"
        Encode(self._pc, encoder_name=enc_name)
        codeword = self._pc.get_codeword()
        return codeword.astype(np.uint8)

    def decode_block(
        self, likelihoods: Union[np.ndarray, Sequence[float]]
    ) -> np.ndarray:
        """
        Decode a single block of N soft LLRs into K information bits using SCD.

        Parameters
        ----------
        likelihoods : np.ndarray or Sequence[float]
            1D array of length N containing channel log-likelihood ratios.

        Returns
        -------
        np.ndarray
            1D array of length K containing decoded binary bits (uint8).
        """
        arr = np.asarray(likelihoods, dtype=np.float64)
        if arr.ndim != 1 or arr.size != self._config.N:
            raise PolarDecodingError(
                f"decode_block expects 1D array of length N={self._config.N}, "
                f"got shape={arr.shape}"
            )

        if np.any(np.isnan(arr)):
            raise PolarDecodingError("decode_block likelihoods array contains NaN values")

        self._pc.likelihoods = arr.copy()
        dec_name = "systematic_scd" if self._config.systematic else "scd"
        Decode(self._pc, decoder_name=dec_name)
        decoded = self._pc.message_received
        return decoded.astype(np.uint8)

    def decode_block_hard(
        self, codeword: Union[np.ndarray, Sequence[int]]
    ) -> np.ndarray:
        """
        Decode a hard binary codeword of length N under noiseless/hard-input conditions.
        """
        llrs = bits_to_llr(codeword, magnitude=self._config.noiseless_llr)
        return self.decode_block(llrs)

    # -----------------------------------------------------------------------
    # Multi-Block / Arbitrary Message Length Operations
    # -----------------------------------------------------------------------
    def encode(
        self, message: Union[np.ndarray, Sequence[int]]
    ) -> Tuple[np.ndarray, int]:
        """
        Encode an arbitrary-length binary message by partitioning into K-bit blocks
        and padding the final block if necessary.

        Parameters
        ----------
        message : np.ndarray or Sequence[int]
            1D binary message of arbitrary length.

        Returns
        -------
        Tuple[np.ndarray, int]
            (concatenated_codewords, pad_count)
            - concatenated_codewords: 1D array of length (num_blocks * N), dtype uint8.
            - pad_count: Number of zero-padding bits appended to the final block (0 <= pad_count < K).
        """
        arr = np.asarray(message, dtype=np.uint8)
        if arr.ndim != 1:
            raise PolarEncodingError(f"Message must be 1D, got ndim={arr.ndim}")

        if arr.size == 0:
            return np.empty(0, dtype=np.uint8), 0

        if not np.all((arr == 0) | (arr == 1)):
            raise PolarEncodingError("Message must contain only binary 0s and 1s")

        padded_msg, pad_count = pad_bits(arr, block_size=self._config.K, pad_value=0)
        num_blocks = padded_msg.size // self._config.K

        codewords = np.empty(num_blocks * self._config.N, dtype=np.uint8)

        for b in range(num_blocks):
            start_in = b * self._config.K
            end_in = start_in + self._config.K
            block_in = padded_msg[start_in:end_in]

            cw = self.encode_block(block_in)

            start_out = b * self._config.N
            end_out = start_out + self._config.N
            codewords[start_out:end_out] = cw

        return codewords, pad_count

    def decode(
        self,
        likelihoods: Union[np.ndarray, Sequence[float]],
        pad_count: int = 0,
    ) -> np.ndarray:
        """
        Decode multi-block soft channel LLRs and remove trailing padding bits.

        Parameters
        ----------
        likelihoods : np.ndarray or Sequence[float]
            1D array of channel LLRs. Length must be an exact multiple of N.
        pad_count : int, default=0
            Number of pad bits to remove from the final decoded block (0 <= pad_count < K).

        Returns
        -------
        np.ndarray
            Reconstructed 1D binary message (uint8).
        """
        arr = np.asarray(likelihoods, dtype=np.float64)
        if arr.ndim != 1:
            raise PolarDecodingError(f"Likelihoods must be 1D, got ndim={arr.ndim}")

        if arr.size == 0:
            if pad_count != 0:
                raise PolarDecodingError(f"pad_count={pad_count} on empty likelihoods stream")
            return np.empty(0, dtype=np.uint8)

        if arr.size % self._config.N != 0:
            raise PolarDecodingError(
                f"Likelihoods length ({arr.size}) must be an exact multiple of N={self._config.N}"
            )

        if pad_count < 0 or pad_count >= self._config.K:
            raise PolarDecodingError(
                f"pad_count must be in [0, K-1] = [0, {self._config.K - 1}], got {pad_count}"
            )

        num_blocks = arr.size // self._config.N
        decoded_bits = np.empty(num_blocks * self._config.K, dtype=np.uint8)

        for b in range(num_blocks):
            start_in = b * self._config.N
            end_in = start_in + self._config.N
            block_llrs = arr[start_in:end_in]

            dec = self.decode_block(block_llrs)

            start_out = b * self._config.K
            end_out = start_out + self._config.K
            decoded_bits[start_out:end_out] = dec

        if pad_count > 0:
            return unpad_bits(decoded_bits, pad_count)
        return decoded_bits

    def decode_hard(
        self,
        codewords: Union[np.ndarray, Sequence[int]],
        pad_count: int = 0,
    ) -> np.ndarray:
        """
        Decode concatenated binary codewords under noiseless/hard-decision conditions.
        """
        llrs = bits_to_llr(codewords, magnitude=self._config.noiseless_llr)
        return self.decode(llrs, pad_count=pad_count)
